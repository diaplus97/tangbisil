// ─── 위기 감지 ───────────────────────────────────────────────

/**
 * 위기 신호 1차 감지 — 프롬프트 지시만 믿지 않기 위한 2중 안전장치.
 *
 * 정밀도보다 재현율을 택했다. 오탐(멀쩡한 사람에게 상담 번호를 보여주는 것)의
 * 비용은 낮고, 미탐의 비용은 되돌릴 수 없다.
 */
const CRISIS_PATTERNS: RegExp[] = [
  /자살/,
  /자해/,
  /죽고\s*싶/,
  /죽어\s*버리/,
  /死/,
  /뛰어내리/,
  /목을?\s*매/,
  /살기\s*싫/,
  /살고\s*싶지\s*않/,
  /사라지고\s*싶/,
  /없어지고\s*싶/,
  /끝내고\s*싶/,
  /더\s*이상\s*못\s*버티/,
  /유서/,
  /수면제.*(먹|모으)/,
  /(내일|다음\s*주).*없을/,
];

export function looksLikeCrisis(text: string): boolean {
  const t = text.replace(/\s+/g, " ");
  return CRISIS_PATTERNS.some((re) => re.test(t));
}

